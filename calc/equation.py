MAX_VALUE = 10000

def solve(a, b, c):
    """Возвращает (вид уравнения, дискриминант, список корней)."""
    # Проверка на недопустимые значения
    if abs(a) > MAX_VALUE or abs(b) > MAX_VALUE or abs(c) > MAX_VALUE:
        raise ValueError("значение вне допустимого диапазона")
    
    # Проверка, является ли это уравнением
    if a == 0 and b == 0:
        raise ValueError("это не уравнение, неизвестное отсутствует")
    
    # Линейное уравнение
    if a == 0:
        return "линейное", None, [-c / b]
    
    # Квадратное уравнение
    d = b * b - 4 * a * c
    if d > 0:
        return "квадратное", d, [(-b + d**0.5) / (2*a), (-b - d**0.5) / (2*a)]
    elif d == 0:
        return "квадратное", d, [-b / (2*a)]
    else:
        return "квадратное", d, []
    